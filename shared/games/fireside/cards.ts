// The Fireside decks. Where Open Book asks what happened to you, these ask what you think and what you'd do,
// so there is rarely a right answer and usually an argument.
//
// Three kinds of card:
//   open   — answered out loud, starting with whoever holds the card
//   choice — everyone picks an option in secret, then the split is revealed
//   who    — everyone names a player in secret, then the tally is revealed

export type Card =
  | { kind: 'open'; text: string }
  | { kind: 'choice'; text: string; options: string[] }
  | { kind: 'who'; text: string };

export interface Deck {
  id: string;
  title: string;
  emoji: string;
  /** After Dark cards are only dealt when the host asks for them. */
  spicy?: boolean;
  cards: Card[];
}

const o = (text: string): Card => ({ kind: 'open', text });
const c = (text: string, ...options: string[]): Card => ({ kind: 'choice', text, options });
const w = (text: string): Card => ({ kind: 'who', text });

